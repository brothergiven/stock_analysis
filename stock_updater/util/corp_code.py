import xml.etree.ElementTree as ET
xml_path = "./CORPCODE.xml"

def get_corp_code_map():
    """
    DART의 corp_code.xml 파일을 파싱해서 stock_code -> corp_code 매핑을 반환
    :param xml_path: 로컬 XML 파일 경로
    :return: dict (stock_code → corp_code)
    """
    tree = ET.parse(xml_path)
    root = tree.getroot()
    stock_to_corp = {}

    for corp in root.findall('list'):
        stock_code = corp.findtext('stock_code', '').strip()
        corp_code = corp.findtext('corp_code', '').strip()

        # stock_code가 비어있지 않은 경우만 저장 (상장기업)
        if stock_code:
            stock_to_corp[stock_code] = corp_code

    return stock_to_corp

